// Downloads the Iconify icons the app uses and bundles them into components/ui/icon-data.ts,
// so icons render instantly and offline (PWA). Run after editing the lists: pnpm icons:fetch
import { writeFile } from "node:fs/promises";

const SETS = {
  solar: [
    "home-2-linear", "home-2-bold",
    "gamepad-linear", "gamepad-bold",
    "cup-star-linear", "cup-star-bold",
    "user-rounded-bold",
    "arrow-left-linear", "arrow-right-linear",
    "alt-arrow-right-linear", "alt-arrow-down-linear",
    "arrow-up-bold", "arrow-right-down-bold", "arrow-right-down-linear",
    "letter-linear", "magnifier-linear",
    "bell-bold", "settings-bold", "camera-bold", "pen-bold",
    "eye-bold", "logout-2-bold", "clipboard-list-bold", "book-bold",
    "info-circle-bold", "question-circle-bold",
    "minus-circle-bold", "target-bold", "check-bold",
    "crown-bold", "chart-2-bold", "lightbulb-bold-duotone",
  ],
  logos: ["google-icon"],
  "token-branded": ["btc", "eth", "sol", "bnb", "xrp"],
};

/** Solar linear icons are drawn at 1.5; the design's icons are chunkier. */
const LINEAR_STROKE = "2.2";

const out = {};
for (const [prefix, names] of Object.entries(SETS)) {
  const res = await fetch(`https://api.iconify.design/${prefix}.json?icons=${names.join(",")}`);
  if (!res.ok) throw new Error(`${prefix}: HTTP ${res.status}`);
  const json = await res.json();
  const missing = names.filter((n) => !json.icons?.[n]);
  if (missing.length) throw new Error(`${prefix}: missing ${missing.join(", ")}`);
  for (const [name, icon] of Object.entries(json.icons)) {
    if (name.endsWith("-linear")) icon.body = icon.body.replaceAll('stroke-width="1.5"', `stroke-width="${LINEAR_STROKE}"`);
  }
  out[prefix] = json;
}

const header = `/* Iconify icon data, bundled locally so nothing is fetched at runtime.
   Generated by scripts/fetch-icons.mjs. Solar (CC BY 4.0), Logos (CC0), Web3 Icons Branded (MIT). Do not edit by hand. */
import type { IconifyJSON } from "@iconify/react";
`;
const body = Object.entries(out)
  .map(([prefix, json]) => `export const ${prefix.toUpperCase().replaceAll("-", "_")}: IconifyJSON = ${JSON.stringify(json)};`)
  .join("\n\n");

await writeFile("components/ui/icon-data.ts", `${header}\n${body}\n`);
console.log("Wrote components/ui/icon-data.ts:", Object.entries(SETS).map(([p, n]) => `${p} ${n.length}`).join(", "));
